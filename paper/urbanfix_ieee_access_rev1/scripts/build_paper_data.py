def cost() -> None:
    lat = max(run("eval", t)["cpu_latency_ms"] for t in DEPLOYED.values())
    per_complaint = 3 * lat
    per_day = int(86400 * 1000 / per_complaint)
    per_day = int(float(f"{per_day:.2g}"))  # two significant figures: an estimate, not a count
    m(name("cost ms per complaint"), f"{per_complaint:.0f}")
    m(name("cost per core day"), thousands(per_day))
    # CPGRAMS: 26.2 lakh grievances in the highest year (submitted paper, refs b3, b4).
    cpgrams_year = 2_620_000
    m(name("cost cpgrams per day"), thousands(round(cpgrams_year / 365)))
    m(name("cost core share"), f"{100 * cpgrams_year / 365 / per_day:.1f}")


