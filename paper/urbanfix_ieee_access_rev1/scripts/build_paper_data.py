# ---------------------------------------------------------------- tests (JUnit reports)
def tests() -> None:
    groups = OrderedDict([
        ("api.test.js", "Intake, workflow guards, scope (the 16 submitted tests) and ward monitoring"),
        ("otp.test.js", "OTP brute force, single use, rate limits"),
        ("concurrency.test.js", "Simultaneous transitions and export quotas"),
        ("audit.test.js", "Hash-chained audit log"),
        ("privacy.test.js", "Photo metadata, text redaction, research keys, k-anonymity, consent"),
        ("registry.test.js", "Registry and tracker allow-lists"),
        ("urgency.test.js", "Server-side urgency (Eq. 2)"),
        ("ai.test.js", "Vision service client, flags and end to end"),
    ])
    counts = defaultdict(lambda: {"tests": 0, "passed": 0, "skipped": 0})
    root = ET.parse(REPO / "backend" / "tests" / "results" / "junit.xml").getroot()
    for case in root.iter("testcase"):
        f = Path(case.get("file", "")).name
        c = counts[f]
        c["tests"] += 1
        if case.find("skipped") is not None:
            c["skipped"] += 1
        elif case.find("failure") is None and case.find("error") is None:
            c["passed"] += 1
    rows, total = [], {"tests": 0, "passed": 0, "skipped": 0}
    for f, label in groups.items():
        c = counts.get(f, {"tests": 0, "passed": 0, "skipped": 0})
        for k in total:
            total[k] += c[k]
        rows.append(f"{label} & {c['tests']} & {c['passed']}" + (r"$^{*}$" if c["skipped"] else "") + r"\\")
    assert sum(c["tests"] for c in counts.values()) == total["tests"], f"unlisted test files: {set(counts) - set(groups)}"
    svc = ET.parse(REPO / "ai_service" / "tests" / "results" / "junit.xml").getroot()
    suite = svc if svc.tag == "testsuite" else svc.find("testsuite")
    s_tests, s_fail = int(suite.get("tests")), int(suite.get("failures")) + int(suite.get("errors"))
    s_skip = int(suite.get("skipped", 0))
    rows.append(r"\midrule")
    rows.append(f"Vision service (FastAPI) & {s_tests} & {s_tests - s_fail - s_skip}" + r"\\")
    write("tab_tests.tex", "\n".join(rows))
    m(name("tests backend"), total["tests"])
    m(name("tests backend passed"), total["passed"])
    m(name("tests backend skipped"), total["skipped"])
    m(name("tests service"), s_tests)
    m(name("tests service passed"), s_tests - s_fail - s_skip)


