# ---------------------------------------------------------------- detection (Table V)
def detection() -> None:
    rows = []
    for cat, tag in DEPLOYED.items():
        ev, tr = run("eval", tag), run("train", tag)
        t = ev["sets"]["test"]
        box = t["box"]
        mask = t.get("mask")
        val = tr["val_metrics_at_best_epoch"]["metrics/mAP50(B)"]
        rows.append(" & ".join([
            LABEL[cat], thousands(t["images"]), f3(box["precision"]["value"]), f3(box["recall"]["value"]),
            ci3(box["mAP50"]), ci3(box["mAP50-95"]), ci3(mask["mAP50"]) if mask else "--",
            f3(val), f"{tr['best_epoch']}/{tr['max_epochs']}"]) + r"\\")
        m(name(cat, "test map"), f3(box["mAP50"]["value"]))
        m(name(cat, "test map lo"), f3(box["mAP50"]["ci95"][0]))
        m(name(cat, "test map hi"), f3(box["mAP50"]["ci95"][1]))
        m(name(cat, "val map"), f3(val))
        m(name(cat, "recall"), f3(box["recall"]["value"]))
        m(name(cat, "precision"), f3(box["precision"]["value"]))
        m(name(cat, "best epoch"), tr["best_epoch"])
        m(name(cat, "cpu ms"), ev["cpu_latency_ms"])
        m(name(cat, "mb"), ev["weights_mb"])
        if mask:
            m(name(cat, "mask map"), f3(mask["mAP50"]["value"]))
    tr = run("train", DEPLOYED["pothole"])
    m(name("max epochs"), tr["max_epochs"])
    m(name("patience"), tr["patience"])
    m(name("img size"), tr["imgsz"])
    m(name("batch"), tr["batch"])
    m(name("bootstrap"), run("eval", DEPLOYED["pothole"])["bootstrap_resamples"])
    lat = [run("eval", t)["cpu_latency_ms"] for t in DEPLOYED.values()]
    m(name("cpu ms min"), min(lat))
    m(name("cpu ms max"), max(lat))
    write("tab_detection.tex", "\n".join(rows))


# ---------------------------------------------------------------- baselines and ablations
def baselines() -> None:
    groups = [("pothole", "pothole", ["yolov8n", "yolo11n", "rtdetr-l"]),
              ("litter", "garbage_litter", ["yolov8n", "yolo11n", "rtdetr-l", "yolov8n-super"]),
              ("graffiti", "graffiti", ["yolov8n", "yolo11n", "rtdetr-l", "yolov8n-scratch"])]
    rows = []
    for cat, key, models in groups:
        first = True
        for model in models:
            tag = (f"{key}_super__yolov8n__s0" if model == "yolov8n-super" else f"{key}__{model}__s0")
            ev, cp = run("eval", tag), run("complaints", tag)
            box = ev["sets"]["test"]["box"]
            t = cp["test"]
            label = LABEL[cat] + (r"$^{a}$" if cat == "pothole" else "") if first else ""
            first = False
            rows.append(" & ".join([
                label, MODEL_LABEL[model], ci3(box["mAP50"]), f"{cp['tau']:.2f}",
                pct(t["valid_false_flag"]["rate"]), pct(t["wrong_false_pass"]["rate"]),
                pct(t["unrelated_false_pass"]["rate"]), f"{ev['cpu_latency_ms']:.0f}", f"{ev['weights_mb']:.1f}"]) + r"\\")
            m(name(cat, model, "map"), f3(box["mAP50"]["value"]))
            m(name(cat, model, "map lo"), f3(box["mAP50"]["ci95"][0]))
            m(name(cat, model, "map hi"), f3(box["mAP50"]["ci95"][1]))
            m(name(cat, model, "cpu ms"), f"{ev['cpu_latency_ms']:.0f}")
            m(name(cat, model, "mb"), f"{ev['weights_mb']:.1f}")
            m(name(cat, model, "wrong pass"), pct(t["wrong_false_pass"]["rate"]))
            m(name(cat, model, "unrelated pass"), pct(t["unrelated_false_pass"]["rate"]))
        rows.append(r"\midrule")
    write("tab_baselines.tex", "\n".join(rows[:-1]))
    mask_super = run("eval", "garbage_litter_super__yolov8n__s0")["sets"]["test"]["mask"]["mAP50"]["value"]
    m(name("litter super mask map"), f3(mask_super))


# ---------------------------------------------------------------- complaint-level screening
def screening() -> None:
    rows = []
    for cat, tag in DEPLOYED.items():
        cp = run("complaints", tag)
        t, t25 = cp["test"], cp["test_at_tau_0.25"]
        road = t.get("road_without_pothole_false_pass")
        rows.append(" & ".join([
            LABEL[cat], f"{cp['tau']:.2f}", rate(t["valid_false_flag"]), rate(t["wrong_false_pass"]),
            rate(t["unrelated_false_pass"]), rate(road) if road else "--"]) + r"\\")
        rows.append(" & ".join([
            r"\quad at $\tau=0.25$", "0.25", rate(t25["valid_false_flag"]), rate(t25["wrong_false_pass"]),
            rate(t25["unrelated_false_pass"]), "--"]) + r"\\")
        m(name(cat, "tau"), f"{cp['tau']:.2f}")
        for k, short in (("valid_false_flag", "flag"), ("wrong_false_pass", "wrong"),
                         ("unrelated_false_pass", "unrelated")):
            m(name(cat, short), pct(t[k]["rate"]))
            m(name(cat, short, "n"), t[k]["n"])
            m(name(cat, short, "twentyfive"), pct(t25[k]["rate"]))
        if road:
            m(name(cat, "road pass"), pct(road["rate"]))
            m(name(cat, "road pass n"), road["n"])
        sim = {r["assumed_invalid_share"]: r for r in cp["workload_simulation"]["rows"]}
        r10 = sim[0.1]
        m(name(cat, "sim flagged"), f"{r10['flagged_per_100']:.1f}")
        m(name(cat, "sim valid flagged"), f"{r10['valid_among_flagged_per_100']:.1f}")
        m(name(cat, "sim invalid passed"), f"{r10['invalid_passed_unflagged_per_100']:.1f}")
        img = cp["image_level_test"]
        m(name(cat, "image recall"), pct(img["recall"]["rate"]))
    flags = [run("complaints", t)["test"]["valid_false_flag"]["rate"] for t in DEPLOYED.values()]
    m(name("flag min"), pct(min(flags)))
    m(name("flag max"), pct(max(flags)))
    m(name("max false flag rule"), "20")
    write("tab_screening.tex", "\n".join(rows))


