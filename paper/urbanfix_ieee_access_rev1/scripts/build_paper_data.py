"""Write every table and number of the revised paper from the committed result files.

    python paper/urbanfix_ieee_access_rev1/scripts/build_paper_data.py

Inputs (all committed): ai_model/results/{train,eval,complaints}/*.json,
ai_model/results/split_report.json, ai_model/results/yolo_sets.json,
analysis/privacy/results/linkage_chicago311.json, backend/tests/load/results/*.json,
backend/tests/results/*.xml and ai_service/tests/results/*.xml (JUnit reports).

Outputs: latex/generated/numbers.tex (one macro per number used in the text) and
latex/generated/tab_*.tex (table bodies). Nothing in these files is typed by hand;
rerun this script after any result changes. Standard library only.
"""
from __future__ import annotations

import glob
import json
import xml.etree.ElementTree as ET
from collections import OrderedDict, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
AI = REPO / "ai_model" / "results"
OUT = Path(__file__).resolve().parents[1] / "latex" / "generated"

DEPLOYED = OrderedDict([("pothole", "pothole_india__yolov8n__s0"),
                        ("litter", "garbage_litter__yolov8n__s0"),
                        ("graffiti", "graffiti__yolov8n__s0")])
LABEL = {"pothole": "Pothole", "litter": "Litter", "graffiti": "Graffiti"}
MODEL_LABEL = {"yolov8n": "YOLOv8n", "yolo11n": "YOLO11n", "rtdetr-l": "RT-DETR-l",
               "yolov8n-scratch": "YOLOv8n, no pretraining", "yolov8n-super": "YOLOv8n, 28 classes"}

macros: "OrderedDict[str, str]" = OrderedDict()


def load(path: Path) -> dict:
    return json.loads(path.read_text())


def run(kind: str, tag: str) -> dict:
    return load(AI / kind / f"{tag}.json")


def f3(x: float) -> str:
    return f"{x:.3f}"


def pct(x: float, nd: int = 1) -> str:
    return f"{100 * x:.{nd}f}"


def ci3(m: dict) -> str:
    lo, hi = m["ci95"]
    return f"{f3(m['value'])} ({f3(lo)}--{f3(hi)})"


def rate(m: dict) -> str:
    lo, hi = m["ci95"]
    return f"{pct(m['rate'])} ({pct(lo)}--{pct(hi)})"


def thousands(n: int) -> str:
    return f"{n:,}"


def name(*parts: str) -> str:
    """Macro name from parts: letters only (LaTeX)."""
    out = ""
    for p in parts:
        for word in p.replace("_", " ").replace("-", " ").split():
            out += word[:1].upper() + word[1:]
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
              "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine", ".": "p"}
    return "n" + "".join(digits.get(c, c) for c in out if c.isalnum() or c == ".")


def m(key: str, value) -> str:
    macros[key] = str(value)
    return str(value)


def write(fname: str, text: str) -> None:
    (OUT / fname).write_text("% Generated by scripts/build_paper_data.py. Do not edit.\n" + text.strip() + "\n")


