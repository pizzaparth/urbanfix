"""Build the phase 3 results tables from the result files, so no number is typed by hand.

    python scripts/summarize.py

Reads results/train, results/eval and results/complaints and writes
results/phase3_summary.md. Every table cell is copied from those JSON files;
rerun this script after any new run. The paper's tables (phase 6) are to be
taken from this output, never from notes or memory.
"""
from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def load(sub: str) -> dict[str, dict]:
    return {p.stem: json.loads(p.read_text()) for p in sorted((R / sub).glob("*.json"))}


def ci(m: dict) -> str:
    lo, hi = m["ci95"]
    return f"{m['value']:.3f} ({lo:.3f}–{hi:.3f})"


def rate(m: dict | None) -> str:
    if not m or m.get("rate") is None:
        return "n/a"
    lo, hi = m["ci95"]
    return f"{m['rate']:.1%} ({lo:.1%}–{hi:.1%}), n={m['n']}"


def main() -> None:
    train, ev, comp = load("train"), load("eval"), load("complaints")
    out = ["# Phase 3 results (generated by scripts/summarize.py; do not edit by hand)", ""]
    out += ["Sources: `results/train/*.json`, `results/eval/*.json`, `results/complaints/*.json`.",
            "Intervals are 95 % bootstrap percentile intervals over images (metrics) or Wilson intervals (rates).", ""]

    out += ["## Training runs", "", "| Run | Device | Epochs run | Best epoch | Minutes | Val mAP50 (box) |", "|---|---|---|---|---|---|"]
    for tag, t in train.items():
        out.append(f"| {tag} | {t.get('device', '?')} | {t.get('epochs_run', '?')} | {t.get('best_epoch', '?')} | "
                   f"{t.get('train_minutes', '?')} | {t.get('val_metrics_at_best_epoch', {}).get('metrics/mAP50(B)', float('nan')):.3f} |")
    out.append("")

    out += ["## Test and external sets (A2, A3, A8)", "",
            "| Run | Set | Images | Box P | Box R | Box mAP50 | Box mAP50-95 | Mask mAP50 | CPU ms | MB |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for tag, e in ev.items():
        for name, s in e["sets"].items():
            b = s["box"]
            mask = ci(s["mask"]["mAP50"]) if "mask" in s else ""
            out.append(f"| {tag} | {name} | {s['images']} | {b['precision']['value']:.3f} | {b['recall']['value']:.3f} | "
                       f"{ci(b['mAP50'])} | {ci(b['mAP50-95'])} | {mask} | {e.get('cpu_latency_ms', '')} | {e.get('weights_mb', '')} |")
    out.append("")
    out.append("CPU latency is only comparable when measured on the same idle machine; see `latency_machine` in each file.")
    out.append("")

    seeds = defaultdict(list)
    for tag, e in ev.items():
        cat_model = tag.rsplit("__s", 1)[0]
        seeds[cat_model].append(e["sets"]["test"]["box"]["mAP50"]["value"])
    multi = {k: v for k, v in seeds.items() if len(v) > 1}
    if multi:
        out += ["## Seed variation (A2)", "", "| Category and model | Seeds | Test box mAP50 mean | min | max |", "|---|---|---|---|---|"]
        for k, v in multi.items():
            out.append(f"| {k} | {len(v)} | {statistics.mean(v):.3f} | {min(v):.3f} | {max(v):.3f} |")
        out.append("")

    out += ["## Complaint-level screening at the chosen tau (A4, A5)", "",
            "| Run | tau | Valid complaints flagged | Wrong-category passed | Unrelated passed | Road without pothole passed |",
            "|---|---|---|---|---|---|"]
    for tag, c in comp.items():
        t = c["test"]
        out.append(f"| {tag} | {c['tau']} | {rate(t.get('valid_false_flag'))} | {rate(t.get('wrong_false_pass'))} | "
                   f"{rate(t.get('unrelated_false_pass'))} | {rate(t.get('road_without_pothole_false_pass'))} |")
    out.append("")
    out += ["Same at the submitted paper's tau = 0.25:", "",
            "| Run | Valid flagged | Wrong passed | Unrelated passed |", "|---|---|---|---|"]
    for tag, c in comp.items():
        t = c["test_at_tau_0.25"]
        out.append(f"| {tag} | {rate(t.get('valid_false_flag'))} | {rate(t.get('wrong_false_pass'))} | {rate(t.get('unrelated_false_pass'))} |")
    out.append("")

    ext = [(tag, n, v) for tag, c in comp.items() for n, v in c.get("external", {}).items()]
    if ext:
        out += ["## External sets at the chosen tau (A3)", "", "| Run | Set | Valid complaints flagged | Image recall |", "|---|---|---|---|"]
        for tag, n, v in ext:
            out.append(f"| {tag} | {n} | {rate(v['valid_false_flag'])} | {rate(v['image_recall'])} |")
        out.append("")

    fair = [(tag, c) for tag, c in comp.items() if "fairness_by_country" in c]
    if fair:
        out += ["## Fairness by country, potholes (A11)", "", "| Run | Country | Image recall | Valid complaints flagged |", "|---|---|---|---|"]
        for tag, c in fair:
            for country, v in c["fairness_by_country"].items():
                out.append(f"| {tag} | {country} | {rate(v['image_recall'])} | {rate(v['complaint_false_flag'])} |")
        out.append("")

    out += ["## Workload simulation (A7; a simulation, not a measure of staff decisions)", "",
            "| Run | Assumed invalid share | Flagged per 100 | Valid among flagged | Invalid passed unflagged |", "|---|---|---|---|---|"]
    for tag, c in comp.items():
        for w in c["workload_simulation"]["rows"]:
            out.append(f"| {tag} | {w['assumed_invalid_share']:.0%} | {w['flagged_per_100']} | "
                       f"{w['valid_among_flagged_per_100']} | {w['invalid_passed_unflagged_per_100']} |")
    out.append("")
    incomplete = [tag for tag, c in comp.items() if not c["test"].get("wrong_false_pass", {}).get("n")]
    if incomplete:
        out += ["**Incomplete:** these runs were scored without the other categories' photos (Colab) and must be "
                "re-scored on the laptop: " + ", ".join(incomplete), ""]
    (R / "phase3_summary.md").write_text("\n".join(out))
    print("wrote", R / "phase3_summary.md", "|", len(train), "runs,", len(ev), "evaluated,", len(comp), "complaint analyses")


if __name__ == "__main__":
    main()
